D = Decimal


# --------------------------------------------------------------------------------------
# Number and period helpers
# --------------------------------------------------------------------------------------

def dec(x) -> Decimal | None:
    if x is None or x == "":
        return None
    return x if isinstance(x, Decimal) else D(str(x))


def q(x: Decimal, places: int) -> Decimal:
    return x.quantize(D(1).scaleb(-places), rounding=ROUND_HALF_UP)


def fmt(x) -> str:
    """Canonical text for a number: no exponent, no trailing zeros."""
    if x is None:
        return ""
    if isinstance(x, bool):
        return "true" if x else "false"
    if isinstance(x, int):
        return str(x)
    x = dec(x)
    if x == x.to_integral_value():
        return str(int(x))
    return format(x.normalize(), "f")


def jnum(x):
    """A number for JSON: int when whole, else float of the canonical text."""
    if x is None:
        return None
    if isinstance(x, int):
        return x
    s = fmt(x)
    return int(s) if "." not in s else float(s)


def period_index(p: str) -> int:
    y, m = p.split("-")
    return int(y) * 12 + int(m) - 1


def period_of(i: int) -> str:
    return f"{i // 12:04d}-{i % 12 + 1:02d}"


def add_months(p: str, n: int) -> str:
    return period_of(period_index(p) + n)


def periods_between(start: str, end: str) -> list[str]:
    return [period_of(i) for i in range(period_index(start), period_index(end) + 1)]


def first_day(p: str) -> dt.date:
    y, m = p.split("-")
    return dt.date(int(y), int(m), 1)


def sha256_text(s: str) -> str:
    return hashlib.sha256(s.encode("utf-8")).hexdigest()


