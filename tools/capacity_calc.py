def build_outputs(model: dict) -> dict[str, str]:
    rows = {**model, **derived_rows(model)}
    out = {}
    for name, (key, fields) in TABLES.items():
        out[f"data/synthetic/{name}"] = render_csv(rows[key], fields)
    out["data/synthetic/events.jsonl"] = render_events(model["events"])
    out["reports/executive-pack/capacity-summary.md"] = doc_capacity_summary(model)
    out["reports/executive-pack/demand-vs-supply.md"] = doc_demand_vs_supply(model)
    out["reports/executive-pack/staffing-signals.md"] = doc_staffing_signals(model)
    out["reports/executive-pack/training-support.md"] = doc_training_support(model)
    out["reports/executive-pack/operating-review.md"] = doc_operating_review(model)
    out["verification/source-precedence-check.md"] = doc_source_precedence(model)
    out["verification/formula-audit.md"] = doc_formula_audit(model)
    out["verification/synthetic-data-check.md"] = doc_synthetic_check(model, out)
    return out


def run(root: Path = ROOT, check: bool = False) -> int:
    model = compute(load_inputs(root))
    outputs = build_outputs(model)
    stale = []
    for rel, text in outputs.items():
        path = root / rel
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current != text:
            stale.append(rel)
            if not check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_bytes(text.encode("utf-8"))
    if check:
        for rel in stale:
            print(f"STALE {rel}")
        print(f"{len(outputs)} generated files; {len(stale)} differ from the calculator")
        return 1 if stale else 0
    print(f"{len(outputs)} generated files; {len(stale)} rewritten")
    return 0


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description="R2 reference capacity calculator.")
    ap.add_argument("--root", default=str(ROOT))
    ap.add_argument("--check", action="store_true", help="exit 1 if any committed output differs")
    a = ap.parse_args(argv)
    return run(Path(a.root).resolve(), a.check)


if __name__ == "__main__":
    sys.exit(main())
