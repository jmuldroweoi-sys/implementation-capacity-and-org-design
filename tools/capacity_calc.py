def gross_available_hours(scheduled, unavailable) -> Decimal:
    return dec(scheduled) - dec(unavailable)


def supply_breakdown(scheduled, unavailable=0, non_project=0, training=0, other=0, ramp_factor=1, mentor=0, places=2) -> dict:
    """One person, one role, one period. Raises ValueError instead of clipping."""
    vals = {k: dec(v) for k, v in dict(scheduled=scheduled, unavailable=unavailable, non_project=non_project,
                                        training=training, other=other, mentor=mentor).items()}
    rf = dec(ramp_factor)
    if any(v < 0 for v in vals.values()):
        raise ValueError("supply hour fields must be non-negative")
    if rf < 0 or rf > 1:
        raise ValueError("ramp_factor must be between 0 and 1")
    gross = gross_available_hours(vals["scheduled"], vals["unavailable"])
    project_available = gross - vals["non_project"] - vals["training"] - vals["other"]
    if gross < 0 or project_available < 0:
        raise ValueError("allowances exceed scheduled hours")
    ramp_adjusted = q(project_available * rf, places)
    ramp_loss = project_available - ramp_adjusted
    effective = ramp_adjusted - vals["mentor"]
    if effective < 0:
        raise ValueError("effective_capacity_hours would be negative")
    return {"gross_available_hours": gross, "project_available_hours": project_available,
            "ramp_adjusted_hours": ramp_adjusted, "ramp_loss_hours": ramp_loss, "effective_capacity_hours": effective}


def capacity_gap_hours(demand, supply) -> Decimal:
    """Shared standard 1.0.0: demand minus capacity. Positive means more work than capacity."""
    return dec(demand) - dec(supply)


def load_ratio(demand, supply, places=4) -> tuple[Decimal | None, str]:
    """demand / supply. Zero supply never divides and never becomes zero."""
    demand, supply = dec(demand), dec(supply)
    if supply == 0:
        return None, "undefined_no_capacity"
    return q(demand / supply, places), "defined"


def training_capacity(learner_count, class_size, track_hours, session_length_hours, prep_hours_per_session,
                      assessment_hours_per_cohort=0, places=2) -> dict:
    learners, size = int(learner_count), int(class_size)
    track, session = dec(track_hours), dec(session_length_hours)
    prep, assess = dec(prep_hours_per_session), dec(assessment_hours_per_cohort or 0)
    if learners < 0 or size <= 0 or track <= 0 or session <= 0 or prep < 0 or assess < 0:
        raise ValueError("invalid training input")
    cohorts = math.ceil(learners / size) if learners else 0
    per_cohort = math.ceil(track / session)
    sessions = cohorts * per_cohort
    delivery = q(cohorts * track, places)
    preparation = q(sessions * prep, places)
    assessment = q(cohorts * assess, places)
    return {"cohorts_required": cohorts, "sessions_per_cohort": per_cohort, "sessions_required": sessions,
            "trainer_delivery_hours": delivery, "trainer_preparation_hours": preparation,
            "trainer_assessment_hours": assessment, "trainer_hours": delivery + preparation + assessment,
            "learner_seat_hours": q(learners * track, places)}


def top_down_hours(effort_hours, effort_share, duration_months, places=2) -> Decimal:
    """Forecast hours for one role in one month of a curve segment: the tier's effort for the
    role times the segment's share, spread evenly across the segment's months."""
    if int(duration_months) < 1 or dec(effort_hours) < 0 or not (0 <= dec(effort_share) <= 1):
        raise ValueError("invalid top-down input")
    return q(dec(effort_hours) * dec(effort_share) / int(duration_months), places)


def golive_support_hours(people_count, hours_per_person_per_day, days, places=2) -> Decimal:
    if int(people_count) < 0 or dec(hours_per_person_per_day) < 0 or dec(days) < 0:
        raise ValueError("invalid launch-support input")
    return q(int(people_count) * dec(hours_per_person_per_day) * dec(days), places)


def latest_staffing_start_date(projected_gap_date: dt.date, hiring_lead_time_days: int, ramp_duration_days: int) -> dt.date:
    return projected_gap_date - dt.timedelta(days=int(hiring_lead_time_days)) - dt.timedelta(days=int(ramp_duration_days))


def evaluate_trigger(above: list[bool], below: list[bool], fire_after: int, clear_after: int) -> list[dict]:
    """Persistence and hysteresis for one rule over consecutive periods.

    Returns one dict per period: state (not_triggered, watch, triggered, clearing) and
    event (fired, cleared, or None). A period that is neither above nor below keeps a
    triggered rule triggered and resets the clearing count; before firing it resets the
    firing count.
    """
    out, state, up, down = [], "not_triggered", 0, 0
    for a, b in zip(above, below):
        event = None
        if state in ("not_triggered", "watch"):
            up = up + 1 if a else 0
            if a and up >= fire_after:
                state, event, down = "triggered", "fired", 0
            else:
                state = "watch" if a else "not_triggered"
        else:
            down = down + 1 if b else 0
            if b and down >= clear_after:
                state, event, up = "not_triggered", "cleared", 0
            else:
                state = "clearing" if b else "triggered"
        out.append({"state": state, "event": event})
    return out


def curve_rows(curve: dict) -> list[dict]:
    """Expand a curve into month offsets with the share for each month."""
    rows, offset = [], 0
    for seg in curve["segments"]:
        months = int(seg["duration_months"])
        for _ in range(months):
            rows.append({"month_offset": offset, "phase_keys": list(seg["phase_keys"]),
                         "effort_share": dec(seg["effort_share"]), "duration_months": months})
            offset += 1
    return rows


def double_count_problems(records: list[dict]) -> list[str]:
    """Authoritative-workload rules for demand records (dicts with the CSV field names)."""
    problems = []
    methods, components = defaultdict(set), defaultdict(list)
    for r in records:
        if r["capacity_inclusion_method"] not in INCLUSION:
            problems.append(f"{r['demand_record_id']}: unknown capacity_inclusion_method")
        if r["demand_method"] not in METHODS:
            problems.append(f"{r['demand_record_id']}: unknown demand_method")
        if r["capacity_inclusion_method"] != "authoritative_workload":
            if not r.get("exclusion_reason"):
                problems.append(f"{r['demand_record_id']}: non-authoritative record without exclusion_reason")
            continue
        methods[(r["project_id"], r["period"])].add(r["demand_method"])
        components[(r["workload_component_id"], r["period"])].append(r["demand_record_id"])
    for (project, period), ms in sorted(methods.items()):
        if len(ms) > 1:
            problems.append(f"{project} {period}: authoritative demand from more than one method ({', '.join(sorted(ms))})")
    for (comp, period), ids in sorted(components.items()):
        if len(ids) > 1:
            problems.append(f"{comp} {period}: authoritative more than once ({', '.join(ids)})")
    return problems


