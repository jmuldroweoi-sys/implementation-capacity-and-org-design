def derived_rows(model: dict) -> dict:
    people_rows = []
    for p in model["people"]:
        ramps = [o for o in p.get("overrides", []) if o["field"] == "ramp_factor" and dec(o["value"]) < 1]
        mentees = sorted({o["mentee"] for o in p.get("overrides", []) if o.get("mentee")})
        for a in p["allocations"]:
            people_rows.append({"person_id": p["person_id"], "person_label": p["label"], "scenario_id": p["scenario_id"],
                                "role_id": a["role_id"], "scheduled_work_hours": a["scheduled_work_hours"],
                                "non_project_hours": a["non_project_hours"], "first_period": p.get("first_period", model["horizon"][0]),
                                "ramp_state": "ramping" if any(o["role_id"] == a["role_id"] for o in ramps) else "fully_ramped",
                                "mentor_of": ";".join(mentees), "unit": "hours", "schema_version": SCHEMA_VERSION})
    trd = [{**t, "project_id": t["project_id"] or "", "covered_by": t.get("covered_by") or "", "source": "r4_interface_fixture",
            "schema_version": SCHEMA_VERSION} for t in model["training_demand"]]
    return {"people_rows": people_rows, "training_demand_rows": trd,
            "scenarios": [{**s, "schema_version": SCHEMA_VERSION} for s in model["scenarios"]]}


def cell(v) -> str:
    if v is None:
        return ""
    if isinstance(v, (list, dict)):
        return json.dumps(v, sort_keys=True, separators=(",", ":"))
    if isinstance(v, (int, float, Decimal, bool)):
        return fmt(v)
    return str(v)


def render_csv(rows: list[dict], fields: list[str]) -> str:
    buf = io.StringIO()
    w = csv.writer(buf, lineterminator="\n")
    w.writerow(fields)
    for r in rows:
        w.writerow([cell(r.get(f)) for f in fields])
    return buf.getvalue()


def render_events(events: list[dict]) -> str:
    return "".join(json.dumps({k: e[k] for k in EVENT_FIELDS}, separators=(",", ":")) + "\n" for e in events)


