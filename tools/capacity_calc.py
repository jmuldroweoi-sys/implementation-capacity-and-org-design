def compute(inp: dict) -> dict:
    P, U = inp["params"], inp["universe"]
    hp, rp = int(P["hours_decimal_places"]), int(P["ratio_decimal_places"])
    horizon = periods_between(P["planning_horizon_start"], P["planning_horizon_end"])
    in_horizon = set(horizon)
    as_of = P["calculation_as_of_at"]
    std_version = str(inp["standard"]["shared_standard_version"])
    source_version = f"r3-{inp['standard']['r3_commit'][:7]}+universe-{U['version']}"
    scenarios = {s["scenario_id"]: s for s in U["scenarios"]}
    projects = {p["project_id"]: p for p in U["projects"]}
    stage_of = {sid: s["org_stage"] for sid, s in scenarios.items()}

    # ---- Demand records: bottom-up from R3, then top-down from tier curves -----------
    demand: list[dict] = []
    skipped_outside_horizon = []
    for r in inp["r3"]:
        if r["period"] not in in_horizon:
            skipped_outside_horizon.append(r["capacity_input_id"])
            continue
        proj = projects[r["project_id"]]
        if stage_of[proj["scenario_id"]] != r["org_stage"]:
            raise ValueError(f"{r['capacity_input_id']}: R3 org_stage differs from the scenario's selected stage")
        method = r["capacity_inclusion_method"]
        reason = {"informational_only": "R3 marks this row informational_only; it is context, never demand",
                  "excluded_to_prevent_double_count": f"R3 marks this row excluded; component {r['workload_component_id']} is counted by its authoritative row"}.get(method, "")
        demand.append({
            "scenario_id": proj["scenario_id"], "project_id": r["project_id"], "period": r["period"], "role_id": r["role_id"],
            "workload_component_id": r["workload_component_id"], "workload_type": r["workload_type"], "demand_method": "bottom_up",
            "source_entity_type": r["source_entity_type"], "source_entity_id": r["source_entity_id"],
            "source_repo": r["source_repo"], "source_version": r["source_version"],
            "import_source_repo": R3_REPO, "import_record_id": r["capacity_input_id"],
            "capacity_inclusion_method": method, "precedence_rank": 1,
            "hours": dec(r["planned_hours"]), "actual_hours": dec(r["actual_hours"]), "unit": "hours", "value_basis": "planned",
            "complexity_tier": proj["complexity_tier"], "curve_id": "", "month_offset": None, "phase_keys": "",
            "exclusion_reason": reason})
    bottom_up_keys = {(d["project_id"], d["period"]) for d in demand if d["capacity_inclusion_method"] == "authoritative_workload"}
    top_down = []
    for proj in U["projects"]:
        tier = inp["tiers"][proj["complexity_tier"]]
        curve = inp["curves"][tier["curve_id"]]
        for cr in curve_rows(curve):
            period = add_months(proj["curve_start_period"], cr["month_offset"])
            if period not in in_horizon:
                continue
            for role_id in sorted(tier["effort_hours_by_role"]):
                hours = top_down_hours(tier["effort_hours_by_role"][role_id], cr["effort_share"], cr["duration_months"], hp)
                covered = (proj["project_id"], period) in bottom_up_keys
                top_down.append({
                    "scenario_id": proj["scenario_id"], "project_id": proj["project_id"], "period": period, "role_id": role_id,
                    "workload_component_id": None, "workload_type": "forecast_project_effort", "demand_method": "top_down",
                    "source_entity_type": "project", "source_entity_id": proj["project_id"],
                    "source_repo": REPO, "source_version": f"demand-drivers-{load_yaml(inp['root'], 'config/demand-drivers.yaml')['version']}",
                    "import_source_repo": "", "import_record_id": "",
                    "capacity_inclusion_method": "excluded_to_prevent_double_count" if covered else "authoritative_workload",
                    "precedence_rank": 3, "hours": hours, "actual_hours": None, "unit": "hours", "value_basis": "forecast",
                    "complexity_tier": proj["complexity_tier"], "curve_id": tier["curve_id"], "month_offset": cr["month_offset"],
                    "phase_keys": "+".join(cr["phase_keys"]),
                    "exclusion_reason": "bottom_up authoritative workload exists for this project and period (precedence rank 1 wins)" if covered else ""})
    top_down.sort(key=lambda d: (d["project_id"], d["period"], d["role_id"]))
    demand += top_down
    for i, d in enumerate(demand, 1):
        d["demand_record_id"] = f"DMN-{i:06d}"
        if d["workload_component_id"] is None:
            d["workload_component_id"] = d["demand_record_id"]
        d["schema_version"] = SCHEMA_VERSION
    problems = double_count_problems(demand)
    if problems:
        raise ValueError("double counting: " + "; ".join(problems))

    # ---- Training ---------------------------------------------------------------------
    training_demand, training_cap = [], []
    for i, t in enumerate(U["training_demand"], 1):
        td = dict(t)
        td["unit_learners"] = "learners"
        training_demand.append(td)
        size = t["class_size"] if t["class_size"] is not None else P["default_class_size"]
        sess = t["session_length_hours"] if t["session_length_hours"] is not None else P["default_session_length_hours"]
        prep = t["prep_hours_per_session"] if t["prep_hours_per_session"] is not None else P["default_prep_hours_per_session"]
        calc = training_capacity(t["learner_count"], size, t["track_hours"], sess, prep, t["assessment_hours_per_cohort"], hp)
        training_cap.append({
            "training_capacity_id": f"TRC-{i:06d}", "training_demand_id": t["training_demand_id"], "scenario_id": t["scenario_id"],
            "project_id": t["project_id"] or "", "period": t["period"], "trainer_role_id": t["trainer_role_id"],
            "learner_count": int(t["learner_count"]), "class_size": int(size),
            "class_size_source": "record" if t["class_size"] is not None else "default_parameter",
            "track_hours": dec(t["track_hours"]), "session_length_hours": dec(sess),
            "session_length_source": "record" if t["session_length_hours"] is not None else "default_parameter",
            "prep_hours_per_session": dec(prep),
            "prep_source": "record" if t["prep_hours_per_session"] is not None else "default_parameter",
            "assessment_hours_per_cohort": dec(t["assessment_hours_per_cohort"] or 0),
            **calc, "capacity_inclusion_method": t["capacity_inclusion_method"], "covered_by": t.get("covered_by") or "",
            "precedence_rank": 2, "schema_version": SCHEMA_VERSION})

    # ---- Launch support ---------------------------------------------------------------
    golive = []
    for g in U["golive_support"]:
        golive.append({**g, "support_hours": golive_support_hours(g["people_count"], g["hours_per_person_per_day"], g["days"], hp),
                       "capacity_inclusion_method": g.get("capacity_inclusion_method", "authoritative_workload"),
                       "value_basis": "forecast", "precedence_rank": 2, "schema_version": SCHEMA_VERSION})

    # ---- Supply -----------------------------------------------------------------------
    supply = []
    for person in U["people"]:
        start = person.get("first_period", horizon[0])
        for alloc in person["allocations"]:
            for period in horizon:
                if period_index(period) < period_index(start):
                    continue
                rec = {"unavailable_hours": 0, "non_project_hours": alloc["non_project_hours"], "training_hours": 0,
                       "other_capacity_reduction_hours": 0, "ramp_factor": 1, "mentor_hours": 0,
                       "mentor_person_id": "", "mentee_person_id": "", "notes": []}
                for o in person.get("overrides", []):
                    if o["period"] == period and o["role_id"] == alloc["role_id"]:
                        rec[o["field"]] = o["value"]
                        if o.get("mentee"):
                            rec["mentee_person_id"] = o["mentee"]
                        if o.get("mentor"):
                            rec["mentor_person_id"] = o["mentor"]
                        if o.get("reason"):
                            rec["notes"].append(o["reason"])
                b = supply_breakdown(alloc["scheduled_work_hours"], rec["unavailable_hours"], rec["non_project_hours"],
                                     rec["training_hours"], rec["other_capacity_reduction_hours"], rec["ramp_factor"],
                                     rec["mentor_hours"], hp)
                supply.append({
                    "scenario_id": person["scenario_id"], "person_id": person["person_id"], "role_id": alloc["role_id"], "period": period,
                    "scheduled_work_hours": dec(alloc["scheduled_work_hours"]), "unavailable_hours": dec(rec["unavailable_hours"]),
                    "gross_available_hours": b["gross_available_hours"], "non_project_hours": dec(rec["non_project_hours"]),
                    "training_hours": dec(rec["training_hours"]), "other_capacity_reduction_hours": dec(rec["other_capacity_reduction_hours"]),
                    "project_available_hours": b["project_available_hours"], "ramp_factor": dec(rec["ramp_factor"]),
                    "ramp_adjusted_hours": b["ramp_adjusted_hours"], "ramp_loss_hours": b["ramp_loss_hours"],
                    "mentor_hours": dec(rec["mentor_hours"]), "effective_capacity_hours": b["effective_capacity_hours"],
                    "mentor_person_id": rec["mentor_person_id"], "mentee_person_id": rec["mentee_person_id"],
                    "ramp_source": "r4_interface_fixture" if dec(rec["ramp_factor"]) < 1 else "fully_ramped_default",
                    "value_basis": "forecast", "unit": "hours", "notes": "; ".join(rec["notes"])})
    supply.sort(key=lambda s: (s["scenario_id"], s["person_id"], s["role_id"], s["period"]))
    for i, s in enumerate(supply, 1):
        s["supply_record_id"] = f"SUP-{i:06d}"
        s["schema_version"] = SCHEMA_VERSION

    # ---- Grid: scenario x role x period ------------------------------------------------
    roles_by_scenario = defaultdict(set)
    for s in supply:
        roles_by_scenario[s["scenario_id"]].add(s["role_id"])
    for d in demand:
        if d["capacity_inclusion_method"] == "authoritative_workload":
            roles_by_scenario[d["scenario_id"]].add(d["role_id"])
    for t in training_cap:
        if t["capacity_inclusion_method"] == "authoritative_workload":
            roles_by_scenario[t["scenario_id"]].add(t["trainer_role_id"])
    for g in golive:
        roles_by_scenario[g["scenario_id"]].add(g["role_id"])
    grid = [(sid, rid, p) for sid in sorted(roles_by_scenario) for rid in sorted(roles_by_scenario[sid]) for p in horizon]

    role_capacity, snapshots = [], []
    by_key_supply = defaultdict(list)
    for s in supply:
        by_key_supply[(s["scenario_id"], s["role_id"], s["period"])].append(s)
    by_key_demand = defaultdict(list)
    for d in demand:
        if d["capacity_inclusion_method"] == "authoritative_workload":
            by_key_demand[(d["scenario_id"], d["role_id"], d["period"])].append(d)
    by_key_training = defaultdict(list)
    for t in training_cap:
        if t["capacity_inclusion_method"] == "authoritative_workload":
            by_key_training[(t["scenario_id"], t["trainer_role_id"], t["period"])].append(t)
    by_key_golive = defaultdict(list)
    for g in golive:
        if g["capacity_inclusion_method"] == "authoritative_workload":
            by_key_golive[(g["scenario_id"], g["role_id"], g["period"])].append(g)

    fields_sum = ("scheduled_work_hours", "unavailable_hours", "gross_available_hours", "non_project_hours", "training_hours",
                  "other_capacity_reduction_hours", "project_available_hours", "ramp_loss_hours", "mentor_hours", "effective_capacity_hours")
    for i, (sid, rid, period) in enumerate(grid, 1):
        sups = by_key_supply[(sid, rid, period)]
        rc = {"role_capacity_id": f"RCP-{i:06d}", "scenario_id": sid, "role_id": rid, "period": period,
              "person_count": len({s["person_id"] for s in sups})}
        for f in fields_sum:
            rc[f] = sum((s[f] for s in sups), D(0))
        rc["supply_record_ids"] = ";".join(s["supply_record_id"] for s in sups)
        rc["schema_version"] = SCHEMA_VERSION
        role_capacity.append(rc)

        dems, trs, gls = by_key_demand[(sid, rid, period)], by_key_training[(sid, rid, period)], by_key_golive[(sid, rid, period)]
        project_h = sum((d["hours"] for d in dems), D(0))
        training_h = sum((t["trainer_hours"] for t in trs), D(0))
        golive_h = sum((g["support_hours"] for g in gls), D(0))
        demand_h = project_h + training_h + golive_h
        supply_h = rc["effective_capacity_hours"]
        ratio, ratio_state = load_ratio(demand_h, supply_h, rp)
        active = sorted({d["project_id"] for d in dems if d["hours"] > 0} | {t["project_id"] for t in trs if t["project_id"]}
                        | {g["project_id"] for g in gls if g["project_id"]})
        tiers = [projects[p]["complexity_tier"] for p in active]
        profile = inp["profiles"][scenarios[sid]["org_profile_id"]]
        max_active = int(profile["planning_settings"]["max_active_projects_per_role"])
        digest_src = {
            "demand_records": [[d["demand_record_id"], fmt(d["hours"])] for d in dems],
            "training_capacity": [[t["training_capacity_id"], fmt(t["trainer_hours"])] for t in trs],
            "golive_support": [[g["golive_support_demand_id"], fmt(g["support_hours"])] for g in gls],
            "supply_records": [[s["supply_record_id"], fmt(s["effective_capacity_hours"])] for s in sups],
            "config_digest": inp["config_digest"], "calculation_version": CALCULATION_VERSION, "standard_version": std_version}
        snapshots.append({
            "capacity_snapshot_id": f"CAP-{i:06d}", "scenario_id": sid, "org_stage": scenarios[sid]["org_stage"], "role_id": rid,
            "period": period, "role_capacity_id": rc["role_capacity_id"],
            "project_demand_hours": project_h, "training_demand_hours": training_h, "golive_support_hours": golive_h,
            "demand_hours": demand_h, "effective_capacity_hours": supply_h, "capacity_gap_hours": capacity_gap_hours(demand_h, supply_h),
            "load_ratio": ratio, "load_ratio_state": ratio_state, "active_project_count": len(active),
            "active_simple_count": tiers.count("simple"), "active_standard_count": tiers.count("standard"),
            "active_complex_count": tiers.count("complex"), "max_active_projects_per_role": max_active,
            "concurrency_state": "above_configured_maximum" if len(active) > max_active else "within_configured_maximum",
            "active_project_ids": ";".join(active),
            "value_basis": "forecast", "source_version": source_version, "config_digest": inp["config_digest"],
            "inputs_digest": sha256_text(json.dumps(digest_src, sort_keys=True, separators=(",", ":"))),
            "calculation_version": CALCULATION_VERSION, "calculated_at": as_of, "standard_version": std_version,
            "schema_version": SCHEMA_VERSION, "_digest_src": digest_src})

    # ---- Triggers -----------------------------------------------------------------------
    rules = {t["staffing_trigger_id"]: t for t in inp["triggers"]["triggers"]}
    upper, lower = dec(P["load_ratio_upper_threshold"]), dec(P["load_ratio_lower_threshold"])
    series = defaultdict(list)
    for s in snapshots:
        series[(s["scenario_id"], s["role_id"])].append(s)
    fires = []
    for key in sorted(series):
        snaps = series[key]
        load_above = [s["load_ratio_state"] == "defined" and s["load_ratio"] >= upper for s in snaps]
        load_below = [(s["load_ratio_state"] == "defined" and s["load_ratio"] <= lower) or s["demand_hours"] == 0 for s in snaps]
        cov_above = [s["load_ratio_state"] == "undefined_no_capacity" and s["demand_hours"] > 0 for s in snaps]
        cov_below = [s["effective_capacity_hours"] > 0 or s["demand_hours"] == 0 for s in snaps]
        results = {
            "STG-000001": evaluate_trigger(load_above, load_below, int(P[rules["STG-000001"]["fire_after_parameter"]]), int(P[rules["STG-000001"]["clear_after_parameter"]])),
            "STG-000002": evaluate_trigger(cov_above, cov_below, int(P[rules["STG-000002"]["fire_after_parameter"]]), int(P[rules["STG-000002"]["clear_after_parameter"]])),
        }
        precedence = inp["triggers"]["combined_state_precedence"]
        for idx, s in enumerate(snaps):
            s["load_trigger_state"] = results["STG-000001"][idx]["state"]
            s["coverage_trigger_state"] = results["STG-000002"][idx]["state"]
            s["trigger_state"] = min((s["load_trigger_state"], s["coverage_trigger_state"]), key=precedence.index)
            s["active_trigger_ids"] = ";".join(r for r in ("STG-000001", "STG-000002") if results[r][idx]["state"] in ("triggered", "clearing"))
            s["trigger_events"] = ";".join(f"{r}:{results[r][idx]['event']}" for r in ("STG-000001", "STG-000002") if results[r][idx]["event"])
            for rule_id in ("STG-000001", "STG-000002"):
                if results[rule_id][idx]["event"] == "fired":
                    above = load_above if rule_id == "STG-000001" else cov_above
                    first = idx
                    while first > 0 and above[first - 1]:
                        first -= 1
                    fires.append({"rule_id": rule_id, "snapshot": s, "streak": snaps[first:idx + 1]})

    # ---- Staffing recommendations -------------------------------------------------------
    rec_types = {r["type"]: r["content"] for r in inp["triggers"]["recommendation_types"]}
    as_of_date = dt.date.fromisoformat(as_of[:10])
    lead, ramp = int(P["hiring_lead_time_days"]), int(P["ramp_duration_days"])
    recommendations = []
    for i, f in enumerate(fires, 1):
        rule = rules[f["rule_id"]]
        snap = f["snapshot"]
        gap_period = f["streak"][0]["period"]
        gap_date = first_day(gap_period)
        latest = latest_staffing_start_date(gap_date, lead, ramp)
        timing = "window_open" if latest >= as_of_date else "window_passed"
        rtype = rule["recommendation_type"]
        content = (f"{rec_types[rtype]} Signal: {rule['name']} fired in {snap['period']} for {snap['role_id']} "
                   f"({snap['scenario_id']}); first affected period {gap_period}. Planning timing under the configured "
                   f"assumptions: latest staffing start {latest.isoformat()} ({gap_date.isoformat()} minus {lead} hiring lead-time "
                   f"days minus {ramp} ramp days), {timing.replace('_', ' ')} as of {as_of_date.isoformat()}. "
                   "This is planning logic only; a named person decides what, if anything, to do.")
        refs = [{"source_type": "capacity_snapshot", "source_id": s["capacity_snapshot_id"]} for s in f["streak"]]
        refs.append({"source_type": "staffing_trigger", "source_id": f["rule_id"]})
        recommendations.append({
            "staffing_recommendation_id": f"STR-{i:06d}", "recommendation_type": rtype, "subject_type": "capacity_snapshot",
            "subject_id": snap["capacity_snapshot_id"], "content": content, "source_references": refs, "status": "proposed",
            "created_at": as_of, "origin_type": "system", "origin_id": f["rule_id"],
            "staffing_trigger_id": f["rule_id"], "scenario_id": snap["scenario_id"], "role_id": snap["role_id"],
            "fired_period": snap["period"], "first_affected_period": gap_period, "capacity_gap_hours": snap["capacity_gap_hours"],
            "projected_gap_date": gap_date.isoformat(), "hiring_lead_time_days": lead, "ramp_duration_days": ramp,
            "latest_staffing_start_date": latest.isoformat(), "timing_state": timing,
            "decision_owner": "named_human", "schema_version": SCHEMA_VERSION})

    # ---- Project ledger (one authoritative method per project and period) ---------------
    project_rows = []
    for proj in U["projects"]:
        r1 = inp["r1_projects"].get(proj["project_id"])
        tier = inp["tiers"][proj["complexity_tier"]]
        curve_periods = {add_months(proj["curve_start_period"], cr["month_offset"]): cr for cr in curve_rows(inp["curves"][tier["curve_id"]])}
        for period in horizon:
            auth = {d["demand_method"] for d in demand if d["project_id"] == proj["project_id"] and d["period"] == period
                    and d["capacity_inclusion_method"] == "authoritative_workload"}
            if not auth and period not in curve_periods:
                continue
            cr = curve_periods.get(period)
            method = next(iter(auth)) if auth else ""
            project_rows.append({
                "project_id": proj["project_id"], "scenario_id": proj["scenario_id"], "project_source": proj["source"],
                "period": period, "curve_phase_keys": "+".join(cr["phase_keys"]) if cr else "",
                "complexity_tier": proj["complexity_tier"], "r1_complexity_profile_id": (r1 or {}).get("complexity_profile_id", "") or "",
                "curve_id": tier["curve_id"], "curve_start_period": proj["curve_start_period"],
                "authoritative_demand_method": method,
                "r1_target_launch_period": (r1["target_launch_date"][:7] if r1 else ""),
                "source_repo": "implementation-operating-system" if r1 else REPO,
                "source_version": inp["standard"]["r1_commit"][:7] if r1 else f"universe-{U['version']}",
                "schema_version": SCHEMA_VERSION})

    # ---- Events ---------------------------------------------------------------------------
    events = []

    def ev(etype, occurred, actor_id, actor_type, subject_type, subject_id, payload):
        events.append({"event_type": etype, "occurred_at": occurred, "actor_id": actor_id, "actor_type": actor_type,
                       "subject_type": subject_type, "subject_id": subject_id, "payload": payload,
                       "source_repo": REPO, "schema_version": std_version})

    for s in sorted(U["scenarios"], key=lambda x: x["selected_at"]):
        ev("org_profile.selected", s["selected_at"], s["selected_by"], "human", "org_profile", s["org_profile_id"], {"org_stage": s["org_stage"]})
    for t in training_cap:
        ev("training_capacity.computed", as_of, t["training_capacity_id"], "system", "training_capacity", t["training_capacity_id"],
           {"period": t["period"], "trainer_hours": jnum(t["trainer_hours"])})
    for g in golive:
        ev("golive_support.computed", as_of, g["golive_support_demand_id"], "system", "golive_support_demand", g["golive_support_demand_id"],
           {"period": g["period"], "project_id": g["project_id"], "support_hours": jnum(g["support_hours"])})
    for s in snapshots:
        ev("capacity.snapshot_computed", as_of, s["capacity_snapshot_id"], "system", "capacity_snapshot", s["capacity_snapshot_id"],
           {"period": s["period"], "demand_hours": jnum(s["demand_hours"]), "supply_hours": jnum(s["effective_capacity_hours"]),
            "capacity_gap_hours": jnum(s["capacity_gap_hours"]), "load_ratio": jnum(s["load_ratio"]), "role_id": s["role_id"]})
    for f, r in zip(fires, recommendations):
        ev("staffing_trigger.fired", as_of, f["rule_id"], "system", "staffing_trigger", f["rule_id"],
           {"period": f["snapshot"]["period"], "rule_id": f["rule_id"], "capacity_gap_hours": jnum(f["snapshot"]["capacity_gap_hours"])})
        ev("staffing_recommendation.recorded", as_of, f["rule_id"], "system", "staffing_recommendation", r["staffing_recommendation_id"],
           {"staffing_trigger_id": f["rule_id"], "status": "proposed"})
    for i, e in enumerate(events, 1):
        e["event_id"] = f"EVT-{i:06d}"

    return {"horizon": horizon, "scenarios": U["scenarios"], "people": U["people"], "projects": project_rows,
            "demand": demand, "training_demand": training_demand, "training_capacity": training_cap, "golive": golive,
            "supply": supply, "role_capacity": role_capacity, "snapshots": snapshots, "recommendations": recommendations,
            "events": events, "skipped_outside_horizon": skipped_outside_horizon, "params": P, "inp": inp}


