def md_table(header: list[str], rows: list[list]) -> str:
    out = ["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"]
    out += ["| " + " | ".join(cell(c) if not isinstance(c, str) else c for c in r) + " |" for r in rows]
    return "\n".join(out)


