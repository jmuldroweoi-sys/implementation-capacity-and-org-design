def load_yaml(root: Path, rel: str):
    return yaml.safe_load((root / rel).read_text(encoding="utf-8"))


def read_csv_rows(path: Path) -> list[dict]:
    with path.open(encoding="utf-8", newline="") as h:
        return list(csv.DictReader(h))


CONFIG_FILES = ("config/parameters.yaml", "config/demand-drivers.yaml", "config/supply-rules.yaml",
                "config/phase-effort-curves.yaml", "config/staffing-triggers.yaml", "config/training-capacity.yaml",
                "config/golive-support.yaml", "profiles/startup.yaml", "profiles/early-scale.yaml",
                "profiles/structured-growth.yaml", "profiles/mature.yaml")


def config_digest(root: Path) -> str:
    h = hashlib.sha256()
    for rel in CONFIG_FILES:
        h.update(rel.encode("utf-8") + b"\n")
        h.update((root / rel).read_bytes().replace(b"\r\n", b"\n"))
    return h.hexdigest()


def load_inputs(root: Path = ROOT) -> dict:
    params = {p["parameter_id"]: p["value"] for p in load_yaml(root, "config/parameters.yaml")["parameters"]}
    profiles = {}
    for name in ("startup", "early-scale", "structured-growth", "mature"):
        prof = load_yaml(root, f"profiles/{name}.yaml")
        profiles[prof["org_profile_id"]] = prof
    return {
        "root": root,
        "params": params,
        "curves": {c["curve_id"]: c for c in load_yaml(root, "config/phase-effort-curves.yaml")["curves"]},
        "tiers": {t["tier_key"]: t for t in load_yaml(root, "config/demand-drivers.yaml")["tiers"]},
        "triggers": load_yaml(root, "config/staffing-triggers.yaml"),
        "profiles": profiles,
        "universe": load_yaml(root, "data/synthetic/universe.yaml"),
        "r3": read_csv_rows(root / "upstream/r3/exports/csv/capacity-inputs.csv"),
        "r1_projects": {r["project_id"]: r for r in read_csv_rows(root / "upstream/r1/data/synthetic/projects.csv")},
        "r1_tasks": {r["task_id"]: r for r in read_csv_rows(root / "upstream/r1/data/synthetic/tasks.csv")},
        "standard": load_yaml(root, "standard/standard-reference.yaml"),
        "config_digest": config_digest(root),
    }


