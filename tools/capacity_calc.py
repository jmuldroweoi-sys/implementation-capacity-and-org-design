def doc_source_precedence(m: dict) -> str:
    out = generated_header("Source-precedence check")
    out += ("This file is regenerated on every run. It proves, from the generated records, that each project and period "
            "has at most one authoritative demand method and each workload component is authoritative at most once.\n\n")
    dem = m["demand"]
    counts = defaultdict(int)
    for d in dem:
        counts[(d["demand_method"], d["capacity_inclusion_method"])] += 1
    rows = [[k[0], k[1], v, fmt(sum((d["hours"] for d in dem if (d["demand_method"], d["capacity_inclusion_method"]) == k), D(0)))]
            for k, v in sorted(counts.items())]
    out += "## Demand records by method and inclusion\n\n" + md_table(["Method", "Inclusion", "Records", "Hours"], rows) + "\n\n"
    keys = defaultdict(set)
    for d in dem:
        if d["capacity_inclusion_method"] == "authoritative_workload":
            keys[(d["project_id"], d["period"])].add(d["demand_method"])
    both = defaultdict(set)
    for d in dem:
        both[(d["project_id"], d["period"])].add(d["demand_method"])
    rows = [[p, per, ", ".join(sorted(both[(p, per)])), ", ".join(sorted(keys[(p, per)]))] for (p, per) in sorted(both) if len(both[(p, per)]) > 1]
    out += "## Project-periods with records from both methods\n\n"
    out += "Each row shows that only one method stays authoritative.\n\n"
    out += md_table(["Project", "Period", "Methods present", "Authoritative method"], rows) + "\n\n"
    probs = double_count_problems(dem)
    out += f"## Result\n\n- Project-periods with authoritative demand: {len(keys)}\n- Project-periods with more than one authoritative method: {sum(1 for v in keys.values() if len(v) > 1)}\n"
    out += f"- Components authoritative more than once in a period: {sum(1 for p in probs if 'authoritative more than once' in p)}\n"
    out += f"- R3 Capacity Inputs rows outside the planning horizon, not imported: {len(m['skipped_outside_horizon'])}\n"
    excl = [t for t in m["training_capacity"] if t["capacity_inclusion_method"] != "authoritative_workload"]
    out += f"- Training records excluded to prevent double counting: {len(excl)} ({', '.join(t['training_demand_id'] + ' covered by ' + t['covered_by'] for t in excl)})\n"
    out += f"- Double-count problems: {len(probs)}\n\n"
    out += f"{SYNTHETIC_FOOTER}\n"
    return out


