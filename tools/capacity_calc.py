"""Reference calculator for implementation-capacity-and-org-design (R2).

Deterministic. No network, no clock, no randomness, no language model. The same inputs
always produce byte-identical outputs. Every calculated number in data/synthetic/,
reports/executive-pack/ (the five reports), and the generated verification documents is
written by this file; nothing calculated is typed by hand.

Inputs (read only):
  config/*.yaml, profiles/*.yaml                      parameters, rules, curves, drivers
  data/synthetic/universe.yaml                        hand-authored synthetic inputs
  upstream/r3/exports/csv/capacity-inputs.csv         pinned R3 Capacity Inputs (bottom-up)
  upstream/r1/...                                     pinned R1 projects, tasks, standard

Usage:
  python tools/capacity_calc.py            regenerate every output
  python tools/capacity_calc.py --check    exit 1 if any committed output differs
"""

